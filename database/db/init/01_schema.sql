-- Schema for the flash-sale benchmark.
-- Shared by the synchronous and the event-driven variant, so both start
-- from exactly the same structure.

CREATE TABLE products (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text           NOT NULL,
    category         text           NOT NULL,
    price            numeric(10,2)  NOT NULL CHECK (price >= 0),
    stock_initial    int            NOT NULL CHECK (stock_initial >= 0),
    stock_available  int            NOT NULL CHECK (stock_available >= 0)
);

-- The same three indexes in both variants. Adding more would change what is measured.
CREATE INDEX ix_products_category ON products (category);
CREATE INDEX ix_products_price    ON products (price);
CREATE INDEX ix_products_name     ON products (name);

CREATE TABLE orders (
    id                uuid         PRIMARY KEY,
    user_id           bigint       NOT NULL CHECK (user_id > 0),
    product_id        bigint       NOT NULL,
    quantity          int          NOT NULL CHECK (quantity BETWEEN 1 AND 5),
    status            text         NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED')),
    rejection_reason  text         NULL
                      CHECK (rejection_reason IN ('OUT_OF_STOCK', 'PRODUCT_NOT_FOUND')),
    idempotency_key   varchar(64)  NOT NULL,
    created_at        timestamptz  NOT NULL,  -- set by the API, not by the database
    processed_at      timestamptz  NULL,
    CONSTRAINT uq_orders_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_orders_rejection CHECK (
        (status = 'REJECTED' AND rejection_reason IS NOT NULL) OR
        (status <> 'REJECTED' AND rejection_reason IS NULL)),
    CONSTRAINT ck_orders_processed CHECK (
        (status = 'PENDING' AND processed_at IS NULL) OR
        (status <> 'PENDING' AND processed_at IS NOT NULL))
);

-- orders.product_id has no foreign key on purpose. The purchase flow inserts the
-- order before it touches stock, and it also stores PRODUCT_NOT_FOUND rejections;
-- a foreign key would make that insert fail. The checks in db/verify/violations.sql
-- cover the missing constraint. user_id has no foreign key either, because there
-- is no users table by design.

